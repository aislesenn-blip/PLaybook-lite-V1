// public/sw.js
const CACHE_NAME = 'playbook-lite-v1';
const urlsToCache = [
  '/',
  '/index.html',
  '/manifest.json'
  // Add other critical assets here if known
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => {
        return cache.addAll(urlsToCache);
      })
  );
});

self.addEventListener('fetch', (event) => {
  event.respondWith(
    caches.match(event.request)
      .then((response) => {
        // Cache hit - return response
        if (response) {
          return response;
        }
        return fetch(event.request);
      })
  );
});
